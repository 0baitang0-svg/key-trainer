import type { Ask, SigType } from '../core/music-theory';

/** 动机音符（音名记法，dur 单位为拍） */
export interface MotifNote {
  /** 音名字母（大写） */
  letter: string;
  /** 八度 */
  oct: number;
  /** 临时记号：1=♯ / -1=♭ / 0=原位 */
  acc: -1 | 0 | 1;
  /** 时值（拍） */
  dur: number;
}

export interface RepertoirePiece {
  id: string;
  title: string;
  composer: string;
  /** 调性标注（如「a 小调」） */
  keyLabel: string;
  type: SigType;
  /** 升/降号个数 0..7 */
  n: number;
  ask: Ask;
  /** 一句中文背景 */
  blurb: string;
  /** 8-16 个音的动机（用于合成播放） */
  motif: MotifNote[];
  /** confirmed=调性与动机已核实；pending=待核对 */
  verify: 'confirmed' | 'pending';
}

